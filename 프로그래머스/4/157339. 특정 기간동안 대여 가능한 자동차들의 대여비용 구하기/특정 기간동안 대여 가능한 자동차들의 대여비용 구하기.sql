SELECT CRCC.CAR_ID, CRCC.CAR_TYPE, (CRCC.DAILY_FEE * (100 - MAX(IFNULL(DISCOUNT_RATE, 0))) / 100) * 30 AS FEE
FROM CAR_RENTAL_COMPANY_CAR CRCC
    LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN CRCDP
    ON CRCC.CAR_TYPE = CRCDP.CAR_TYPE
    AND CRCDP.DURATION_TYPE = '30일 이상'
    JOIN CAR_RENTAL_COMPANY_RENTAL_HISTORY CRCRH
    ON CRCC.CAR_ID = CRCRH.CAR_ID
WHERE (CRCC.CAR_TYPE = '세단' OR CRCC.CAR_TYPE = 'SUV')
AND NOT EXISTS (
    SELECT * FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY CRCR
    WHERE CRCR.START_DATE <= '2022-11-30'
    AND CRCR.END_DATE >= '2022-11-01'
    AND CRCR.CAR_ID = CRCC.CAR_ID
)
GROUP BY CRCC.CAR_ID
HAVING FEE >= 500000 AND FEE < 2000000
ORDER BY FEE DESC, CRCC.CAR_TYPE ASC, CAR_ID DESC;